import * as T from '/vendor/three/three.module.js';

const textures = new T.TextureLoader();
const geometryLoader = new T.BufferGeometryLoader();
const asset = name => new URL('./assets/' + name, import.meta.url).href;

function texture(name, colorSpace, anisotropy) {
  return textures.loadAsync(asset(name + '.webp')).then(map => {
    map.colorSpace = colorSpace;
    map.anisotropy = anisotropy;
    return map;
  }).catch(() => null);
}

export async function loadArt(anisotropy) {
  const surfaces = {};
  const props = {};
  await Promise.all([
    ...['asphalt', 'pavers', 'plaster', 'deck', 'sand'].map(async name => {
      const [map, normalMap] = await Promise.all([
        texture(name, T.SRGBColorSpace, anisotropy),
        texture(name + '-normal', T.NoColorSpace, anisotropy),
      ]);
      for (const image of [map, normalMap]) {
        if (image) image.wrapS = image.wrapT = T.RepeatWrapping;
      }
      if (map) surfaces[name] = { map, normalMap };
    }),
    ...['bench', 'planter'].map(async name => {
      try {
        const response = await fetch(asset(name + '.json'));
        if (!response.ok) return;
        const [data, map] = await Promise.all([response.json(), texture(name, T.SRGBColorSpace, anisotropy)]);
        if (map) map.flipY = false;
        props[name] = {
          geometry: geometryLoader.parse(data),
          material: new T.MeshStandardMaterial({ map, roughness: .83 }),
        };
      } catch {
        // The geometry generated by the city remains available.
      }
    }),
  ]);
  const sky = await texture('sky', T.SRGBColorSpace, 1);
  if (sky) sky.mapping = T.EquirectangularReflectionMapping;
  return { surfaces, props, sky };
}

export function tiledSurface(options, repeat) {
  const result = new T.MeshStandardMaterial(options);
  result.normalScale.setScalar(.53);
  result.onBeforeCompile = shader => {
    shader.uniforms.tilesPerMetre = { value: repeat };
    shader.vertexShader = 'uniform float tilesPerMetre;\n' + shader.vertexShader.replace('#include <uv_vertex>', `
      #include <uv_vertex>
      // Each orientation of the box tiles by physical size, including on instanced buildings.
      vec3 dimensions = vec3(length(instanceMatrix[0].xyz), length(instanceMatrix[1].xyz), length(instanceMatrix[2].xyz));
      vec3 surface = (position + 0.5) * dimensions;
      vec2 tiles = (abs(normal.y) > 0.5 ? surface.xz : abs(normal.x) > 0.5 ? surface.zy : surface.xy) * tilesPerMetre;
      #ifdef USE_MAP
        vMapUv = tiles;
      #endif
      #if defined(USE_NORMALMAP)
        vNormalMapUv = tiles;
      #endif
    `);
  };
  return result;
}

export function createSea(scene) {
  const light = new T.Vector3(-.72, .31, .62).normalize();
  const uniforms = { time: { value: 0 }, sunlight: { value: light } };
  const material = new T.ShaderMaterial({
    uniforms,
    vertexShader: `
      varying vec3 surface;
      void main() {
        surface = (modelMatrix * vec4(position, 1.)).xyz;
        gl_Position = projectionMatrix * viewMatrix * vec4(surface, 1.);
      }`,
    fragmentShader: `
      uniform float time;
      uniform vec3 sunlight;
      varying vec3 surface;
      void main() {
        vec2 p = surface.xz;
        float r1 = sin(p.x * 1.26 + p.y * 0.87 + time * 1.6);
        float r2 = sin(p.x * 0.55 - p.y * 2.48 + time * 2.3);
        float r3 = sin(p.x * 3.9 + p.y * 1.17 - time * 2.7);
        vec3 n = normalize(vec3(0.035*r1 + 0.020*r3, 1., 0.11*r2 + 0.04*r3));
        vec3 eye = normalize(cameraPosition - surface);
        float fresnel = pow(1. - max(dot(eye,n),0.), 3.6);
        float specular = pow(max(dot(reflect(-sunlight,n),eye),0.), 56.);
        float shore = 1. - smoothstep(101.,122.,p.y);
        vec3 c = mix(vec3(0.022,0.19,0.23),vec3(0.065,0.40,0.37),shore);
        c = mix(c,vec3(0.28,0.45,0.53),fresnel * 0.80);
        c += vec3(0.94,0.62,0.39) * specular * (0.75 + 0.24*r3);
        float wash = 1. - smoothstep(0.1,0.77,abs(p.y - 97.15 - 0.5 * sin(p.x*.3 - time*1.8)));
        c = mix(c,vec3(.65,.80,.77),wash * (0.3 + 0.18*r2));
        float haze = smoothstep(115.,355.,distance(surface,cameraPosition));
        c = mix(c,vec3(.31,.53,.59),haze);
        gl_FragColor = vec4(c,1.);
        #include <tonemapping_fragment>
        #include <colorspace_fragment>
      }`,
  });
  const mesh = new T.Mesh(new T.PlaneGeometry(1250, 1080), material);
  mesh.rotation.x = -Math.PI / 2;
  mesh.position.set(0, -.11, 305);
  scene.add(mesh);
  return uniforms.time;
}
